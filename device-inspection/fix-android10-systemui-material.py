def write(p, s):
    p.parent.mkdir(parents=True, exist_ok=True)
    if not p.exists() or p.read_text() != s:
        p.write_text(s)


def edit(p, fn):
    s = p.read_text()
    t = fn(s)
    if t != s:
        p.write_text(t)


def sub1(old, new, tag):
    """replace `old` once unless `tag` already present."""
    def f(s):
        if tag in s:
            return s
        if old not in s:
            raise SystemExit('anchor missing for ' + tag + ': ' + old[:60])
        return s.replace(old, new, 1)
    return f


