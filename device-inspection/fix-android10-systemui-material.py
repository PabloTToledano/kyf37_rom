def theme_items(s):
    if 'kyf37-material-theme' in s:
        return s
    items = {
        'Theme.SystemUI': ['android:colorAccent', 'android:colorControlActivated'],
        'qs_theme': ['android:colorAccent', 'android:colorControlActivated', 'android:colorBackgroundFloating', 'android:dialogCornerRadius'],
        'Theme.SystemUI.Dialog': ['android:colorAccent', 'android:colorControlActivated', 'android:colorBackgroundFloating', 'android:dialogCornerRadius'],
        'Theme.SystemUI.Dialog.GlobalActions': ['android:colorAccent', 'android:colorControlActivated'],
    }
    vals = {'android:colorAccent': '@color/kyf37_m_primary', 'android:colorControlActivated': '@color/kyf37_m_primary',
            'android:colorBackgroundFloating': '@color/kyf37_m_card', 'android:dialogCornerRadius': '28dp'}
    for name, keys in items.items():
        body = ''.join('        <item name="%s">%s</item><!-- kyf37-material-theme -->\n' % (k, vals[k]) for k in keys)
        m = re.search(r'(<style name="%s"[^>]*?)(/>|>)' % re.escape(name), s)
        if not m:
            raise SystemExit('style missing ' + name)
        if m.group(2) == '/>':
            s = s[:m.start()] + m.group(1) + '>\n' + body + '    </style>' + s[m.end():]
        else:
            s = s[:m.end()] + '\n' + body.rstrip('\n') + s[m.end():]
    return s


edit(root / 'res/values/styles.xml', theme_items)


